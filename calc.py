def sum(first: int, second: int) -> int:
    """
        Функция для суммирования чисел

        :param first : Первое число
        :param second : Второе число
        :return : Сумма чисел
    """
    return first + second

def sub (first : int, second : int) -> int:
    return first - second

def mult (first : int, second : int) -> int:
    return first * second

def div (first : int , second : int) -> int:
    return first / second


